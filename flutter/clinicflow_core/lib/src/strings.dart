class Strings {
  const Strings(this.lang);
  final String lang;

  String t(String key, [Map<String, String> vars = const {}]) {
    var s = (_text[lang] ?? _text['en']!)[key] ?? _text['en']![key] ?? key;
    vars.forEach((k, v) => s = s.replaceAll('{$k}', v));
    return s;
  }

  bool get fr => lang == 'fr';

  /// A visit's status, in words.
  String status(ApptStatus st) => fr ? _statusFr[st]! : st.label;

  /// "Mon" / "lun." for a weekday key ('Mon'...'Sun').
  String weekday(String key) => fr ? const {'Mon': 'lun.', 'Tue': 'mar.', 'Wed': 'mer.', 'Thu': 'jeu.', 'Fri': 'ven.', 'Sat': 'sam.', 'Sun': 'dim.'}[key] ?? key : key;

  String dayPart(DayPart p) => fr ? const {DayPart.morning: 'Matin', DayPart.afternoon: 'Après-midi', DayPart.after4: 'Après 16 h'}[p]! : p.label;

  String kind(NoticeKind k) => fr ? const {NoticeKind.reminder: 'Rappel', NoticeKind.todo: 'À faire', NoticeKind.update: 'Mise à jour', NoticeKind.offer: 'Offre', NoticeKind.notice: 'Avis'}[k]! : k.label;

  /// Relationships and visit types are stored in English; these show them in the app's language.
  String relationship(String r) => fr ? const {'Child': 'Enfant', 'Parent': 'Parent', 'Partner': 'Conjoint·e', 'Other': 'Autre'}[r] ?? r : r;
  String visitType(String v) =>
      fr ? const {'Follow-up visit': 'Visite de suivi', 'First visit at this clinic': 'Première visite à cette clinique', 'Routine check': 'Examen de routine'}[v] ?? v : v;

  /// "$40.00" / "40,00 $".
  String money(double amount) => fr ? '${amount.toStringAsFixed(2).replaceAll('.', ',')} \$' : '\$${amount.toStringAsFixed(2)}';

